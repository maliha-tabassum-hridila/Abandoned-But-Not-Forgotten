#!/usr/bin/env node
/* Validates data/objects.geojson and data/strings.json, then writes
   js/objects-data.js and js/strings-data.js so the site also works when
   opened by double-click (file:// blocks fetch of .json files).
   Usage: node tools/build-data.js          (build + validate)
          node tools/build-data.js --check  (validate + confirm generated files are in sync)
   No network. No dependencies. */
"use strict";
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const errors = [];
const err = (m) => errors.push(m);
const check = process.argv.includes("--check");

const fc = JSON.parse(read("data/objects.geojson"));
const strings = JSON.parse(read("data/strings.json"));
const VER = ["source-checked", "archive-text", "needs-check"];
const DATE = /^\d{4}-\d{2}(-\d{2})?$/;
const ids = new Set();
const missionIds = (() => { const m = read("js/data.js").match(/id:\s*"([a-z0-9-]+)"/g) || []; return new Set(m.map(s => s.match(/"(.*)"/)[1])); })();

if (fc.type !== "FeatureCollection") err("objects.geojson must be a FeatureCollection");
fc.features.forEach((f, i) => {
  const p = f.properties || {}, where = "feature " + i + " (" + (p.id || "?") + ")";
  if (!p.id || !/^[a-z0-9-]+$/.test(p.id)) err(where + ": bad id");
  if (ids.has(p.id)) err(where + ": duplicate id"); ids.add(p.id);
  if (f.id !== p.id) err(where + ": feature id must equal properties.id");
  if (!["moon", "mars"].includes(p.body)) err(where + ": body must be moon or mars");
  const c = f.geometry && f.geometry.coordinates;
  if (!c || c.length !== 2 || !(c[0] >= -180 && c[0] <= 180) || !(c[1] >= -90 && c[1] <= 90)) err(where + ": coordinates must be [lon -180..180, lat -90..90]");
  if (!missionIds.has(p.mission_id)) err(where + ": mission_id '" + p.mission_id + "' not found in js/data.js");
  ["landed", "left_behind", "last_contact", "mission_closed"].forEach(k => { if (p[k] != null && !DATE.test(p[k])) err(where + ": " + k + " must be YYYY-MM-DD or YYYY-MM or null"); });
  if (p.left_behind && !p.left_behind_basis) err(where + ": left_behind needs left_behind_basis");
  if (!p.coord_convention) err(where + ": missing coord_convention");
  if (!p.why_left || !p.science) err(where + ": missing why_left/science text");
  if (!Array.isArray(p.sources) || !p.sources.length) err(where + ": needs at least one source");
  (p.sources || []).forEach(s => { if (!/^https:\/\//.test(s.url || "")) err(where + ": source url must be https"); if (!s.label || !s.id) err(where + ": source needs label and id"); });
  const v = p.verification || {};
  ["coordinates", "dates", "identifiers", "narrative"].forEach(k => { const val = String(v[k] || ""); if (!VER.some(x => val.startsWith(x))) err(where + ": verification." + k + " invalid"); });
});
/* Consistency with the older per-mission sites in js/data-extra.js (approximate, about +/-0.5 deg). */
try {
  const vm = require("vm"), ctx = {}; vm.createContext(ctx);
  vm.runInContext(read("js/data.js") + "\n" + read("js/data-extra.js") + ";this.X = MISSION_EXTRAS;", ctx);
  fc.features.forEach(f => {
    const p = f.properties, sites = (ctx.X[p.mission_id] || {}).sites || []; if (!sites.length) return;
    const lon = p.body === "mars" ? (f.geometry.coordinates[0] + 360) % 360 : f.geometry.coordinates[0], lat = f.geometry.coordinates[1];
    const d = Math.min.apply(null, sites.map(s => Math.hypot(s.lat - lat, ((s.lon - lon + 540) % 360) - 180)));
    if (d > 1.0) err(p.id + ": coordinates differ from js/data-extra.js by " + d.toFixed(2) + " deg");
  });
} catch (e) { err("could not cross-check data-extra.js: " + e.message); }
const en = Object.keys(strings.en).sort(), bn = Object.keys(strings.bn).sort();
en.filter(k => !strings.bn[k]).forEach(k => err("strings: bn missing " + k));
bn.filter(k => !strings.en[k]).forEach(k => err("strings: en missing " + k));

if (errors.length) { console.error("VALIDATION FAILED\n - " + errors.join("\n - ")); process.exit(1); }

const banner = "/* GENERATED by tools/build-data.js from data/*.json. Do not edit by hand. */\n";
const out = {
  "js/objects-data.js": banner + "window.OBJECTS_GEOJSON = " + JSON.stringify(fc) + ";\n",
  "js/strings-data.js": banner + "window.STRINGS = " + JSON.stringify({ en: strings.en, bn: strings.bn }) + ";\n"
};
let drift = false;
Object.keys(out).forEach(f => {
  const fp = path.join(root, f);
  if (check) { if (!fs.existsSync(fp) || fs.readFileSync(fp, "utf8") !== out[f]) { console.error("OUT OF SYNC: " + f + " (run node tools/build-data.js)"); drift = true; } }
  else fs.writeFileSync(fp, out[f]);
});
if (drift) process.exit(1);
console.log((check ? "OK (in sync): " : "Built: ") + fc.features.length + " objects, " + en.length + " strings per language.");
